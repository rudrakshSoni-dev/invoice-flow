/**
 * Runs real extraction over every fixture invoice and scores each field against the manifest.
 * Requires LLM_API_KEY. Writes docs/eval.md.
 *   pnpm --filter api eval
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { extractInvoice } from '../src/agent/extract.stage';
import { loadEnv } from '../src/common/env';
import { GEMINI_DEFAULT_MODEL, GeminiProvider } from '../src/llm/gemini.provider';
import { GROQ_DEFAULT_MODEL, GroqProvider } from '../src/llm/groq.provider';
import { LlmError, type LlmProvider } from '../src/llm/llm-provider';
import { generateStructured } from '../src/llm/structured-output';
import { FIXTURE_DIR, type FixtureInvoice, loadFixtureManifest } from './fixture-manifest';

const TARGET_ACCURACY = 0.9;
const TRANSIENT_RETRIES = 4;
const SCALAR_FIELDS = [
  'vendorName',
  'vendorTaxId',
  'invoiceNumber',
  'poNumber',
  'issueDate',
  'dueDate',
  'currency',
  'subtotal',
  'tax',
  'total',
] as const;

type FieldScore = { field: string; ok: boolean; expected: unknown; actual: unknown };

const normalize = (value: unknown) =>
  typeof value === 'string' ? value.trim().toLowerCase().replace(/\s+/g, ' ') : value;
const sameAmount = (a: string, b: string) => Number(a) === Number(b);

// The app's job worker retries transient provider errors; the eval does the same so one 503 doesn't end the run.
function withTransientRetry(provider: LlmProvider): LlmProvider {
  return {
    name: provider.name,
    async generateJson(request) {
      for (let attempt = 0; ; attempt++) {
        try {
          return await provider.generateJson(request);
        } catch (error) {
          if (!(error instanceof LlmError && error.retryable) || attempt >= TRANSIENT_RETRIES)
            throw error;
          await new Promise((resolve) => setTimeout(resolve, 2_000 * 2 ** attempt));
        }
      }
    },
  };
}

async function scoreFixture(fixture: FixtureInvoice, provider: LlmProvider) {
  const pdf = readFileSync(join(FIXTURE_DIR, fixture.file));
  const result = await extractInvoice(pdf, (req) =>
    generateStructured(provider, async () => {}, req),
  );
  const expected = fixture.expected;
  const scores: FieldScore[] = [
    {
      field: 'isInvoice',
      ok: result.ok === expected.isInvoice,
      expected: expected.isInvoice,
      actual: result.ok,
    },
  ];

  if (expected.isInvoice) {
    const actual = result.ok ? result.fields : undefined;
    for (const field of SCALAR_FIELDS) {
      const a = actual?.[field] ?? null;
      const e = expected[field];
      const ok = ['subtotal', 'tax', 'total'].includes(field)
        ? typeof a === 'string' && typeof e === 'string' && sameAmount(a, e)
        : normalize(a) === normalize(e);
      scores.push({ field, ok, expected: e, actual: a });
    }
    const linesOk =
      actual !== undefined &&
      actual.lineItems.length === expected.lineItems.length &&
      expected.lineItems.every((line, i) => {
        const got = actual.lineItems[i];
        return (
          got !== undefined &&
          got.quantity === line.quantity &&
          sameAmount(got.unitPrice, line.unitPrice) &&
          sameAmount(got.total, line.total)
        );
      });
    scores.push({
      field: 'lineItems',
      ok: linesOk,
      expected: expected.lineItems.length,
      actual: actual?.lineItems.length ?? null,
    });
  }

  return {
    file: fixture.file,
    mode: result.mode,
    attempts: result.attempts,
    confidence: result.ok ? result.confidence : null,
    scores,
  };
}

async function main(): Promise<void> {
  const env = loadEnv();
  if (!env.LLM_API_KEY) throw new Error('Set LLM_API_KEY in .env to run the extraction eval');
  const isGroq = env.LLM_PROVIDER === 'groq';
  const defaultModel = isGroq ? GROQ_DEFAULT_MODEL : GEMINI_DEFAULT_MODEL;
  const model = env.LLM_MODEL || defaultModel;
  const provider = withTransientRetry(
    isGroq ? new GroqProvider(env.LLM_API_KEY, model) : new GeminiProvider(env.LLM_API_KEY, model),
  );

  const results = [];
  for (const fixture of loadFixtureManifest()) {
    process.stdout.write(`${fixture.file} ... `);
    const result = await scoreFixture(fixture, provider);
    const correct = result.scores.filter((s) => s.ok).length;
    console.log(`${correct}/${result.scores.length}`);
    results.push(result);
  }

  const all = results.flatMap((r) => r.scores);
  const accuracy = all.filter((s) => s.ok).length / all.length;
  const pct = (n: number) => `${(n * 100).toFixed(1)}%`;
  const misses = results.flatMap((r) =>
    r.scores
      .filter((s) => !s.ok)
      .map(
        (s) =>
          `| ${r.file} | ${s.field} | \`${JSON.stringify(s.expected)}\` | \`${JSON.stringify(s.actual)}\` |`,
      ),
  );

  const report = [
    '# Extraction eval',
    '',
    `Generated by \`pnpm --filter api eval\` on ${new Date().toISOString().slice(0, 10)} with \`${model}\`.`,
    '',
    `**Field accuracy: ${pct(accuracy)}** (${all.filter((s) => s.ok).length}/${all.length} fields, target ${pct(TARGET_ACCURACY)})`,
    '',
    '| Fixture | Mode | Attempts | Confidence | Fields correct |',
    '| --- | --- | --- | --- | --- |',
    ...results.map(
      (r) =>
        `| ${r.file} | ${r.mode} | ${r.attempts} | ${r.confidence ?? 'n/a'} | ${r.scores.filter((s) => s.ok).length}/${r.scores.length} |`,
    ),
    '',
    '## Misses',
    '',
    ...(misses.length
      ? ['| Fixture | Field | Expected | Actual |', '| --- | --- | --- | --- |', ...misses]
      : ['None.']),
    '',
  ].join('\n');

  writeFileSync(join(__dirname, '../../../docs/eval.md'), report);
  console.log(`\nField accuracy ${pct(accuracy)}; wrote docs/eval.md`);
  if (accuracy < TARGET_ACCURACY) process.exitCode = 1;
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
